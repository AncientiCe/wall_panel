"""Convert a PNG logo into an LVGL 8 image (RGB565 + alpha) C file.

Usage: python tools/make_logo.py <logo.png> <height_px> src/assets/img_logo.c
The transparent border is cropped first; transparency is kept.
"""
import sys
from PIL import Image

src, height, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
im = Image.open(src).convert("RGBA")
im = im.crop(im.getbbox())
width = round(im.width * height / im.height)
im = im.resize((width, height), Image.LANCZOS)

data = bytearray()
for r, g, b, a in im.getdata():
    if a == 0:
        r = g = b = 0
    c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    data += bytes((c & 0xFF, c >> 8, a))  # LV_COLOR_16_SWAP 0: low byte first

lines = []
for i in range(0, len(data), 24):
    lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")

with open(out, "w", newline="\n") as f:
    f.write(f"""// Generated by tools/make_logo.py from {src.replace(chr(92), '/').split('/')[-1]}; do not edit.
#include <lvgl.h>

static const uint8_t img_logo_map[] = {{
{chr(10).join(lines)}
}};

const lv_img_dsc_t img_logo = {{
    .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = {width}, .h = {height}}},
    .data_size = {len(data)},
    .data = img_logo_map,
}};
""")
print(f"{out}: {width}x{height}, {len(data)} bytes")
